-- ============================================================
-- INGRESANTES 2027  ·  quién quiere entrar al grupo de WhatsApp
--
-- La pantalla `ingreso/` tiene un formulario «Sumate al grupo»: quien
-- empieza en 2027 deja su nombre, su WhatsApp, la carrera y de dónde
-- viene, y alguien de la agrupación lo suma al grupo de ingresantes de
-- su carrera. Se mira desde el panel, en la solapa «Ingresantes».
--
-- Lo decidido el 24/10/2026 (Máximo):
--
--   CUATRO DATOS Y NADA MÁS. Nombre, WhatsApp y carrera para sumar a
--   alguien al grupo que le toca; la localidad para saber cuántes no son
--   de La Plata (grupos de viaje, mandarles Cómo llegar). Sin mail, sin
--   DNI, sin edad.
--
--   LO VE SOLO EL EQUIPO. Escribe cualquiera sin cuenta, igual que las
--   consultas de Avisanos, pero leer, marcar y borrar es solo del rol
--   `equipo`. Nadie de afuera puede ver la lista, ni la propia fila.
--
--   SIN FECHA DE BORRADO. Queda como base de ingresantes y se borra a
--   mano desde el panel (de a uno o todo junto) cuando se decida. Lo que
--   sí hay: quien se anotó se puede BORRAR SOLA desde el mismo teléfono,
--   con la marca al azar que guarda la app (`bolivar-ingreso-grupo`),
--   como el «Voy». Sin eso, salir de la lista era pedírselo a alguien.
--
--   UNA FILA POR NÚMERO. Si se anota dos veces (otro teléfono, o corrigió
--   el nombre), se pisa la fila vieja y no se duplica, y se conserva si
--   ya estaba en el grupo.
--
-- Todo entra por funciones `security definer` que miran lo que reciben;
-- la tabla está cerrada para `anon`.
--
-- Cómo se corre:
--   supabase.com -> proyecto -> SQL Editor -> New query -> pegar -> Run
-- Se puede correr más de una vez sin romper nada.
-- ============================================================


-- ------------------------------------------------------------
-- 1. LA TABLA
-- ------------------------------------------------------------
create table if not exists public.ingresantes (
  id          bigint generated by default as identity primary key,
  nombre      text   not null check (char_length(nombre) between 2 and 80),
  -- Solo dígitos, con código de país: lo arma la base a partir de lo que
  -- escribieron (ver `anotar_ingresante`), así el panel abre el chat
  -- con wa.me sin adivinar.
  telefono    text   not null unique check (telefono ~ '^[0-9]{10,15}$'),
  carrera     text   not null check (carrera in ('ts', 'tgcr', 'fono', 'nose')),
  localidad   text   check (char_length(localidad) <= 80),
  marca       text   not null unique check (marca ~ '^[0-9a-f]{32}$'),
  -- Lo tilda el equipo cuando ya la sumó. Sirve para no escribirle dos
  -- veces a la misma persona entre varias compañeras.
  en_el_grupo boolean not null default false,
  creado_at   timestamptz not null default now()
);

create index if not exists ingresantes_carrera_idx
  on public.ingresantes (carrera, en_el_grupo, creado_at desc);

alter table public.ingresantes enable row level security;

revoke all on public.ingresantes from anon, authenticated;
grant select, update, delete on public.ingresantes to authenticated;
-- El equipo solo tilda «en el grupo»: el resto lo escribió la persona.
revoke update on public.ingresantes from authenticated;
grant update (en_el_grupo) on public.ingresantes to authenticated;

drop policy if exists "ingresantes los ve el equipo" on public.ingresantes;
create policy "ingresantes los ve el equipo"
  on public.ingresantes for select to authenticated
  using ((select public.es_equipo()));

drop policy if exists "ingresantes el equipo los marca" on public.ingresantes;
create policy "ingresantes el equipo los marca"
  on public.ingresantes for update to authenticated
  using ((select public.es_equipo())) with check ((select public.es_equipo()));

drop policy if exists "ingresantes el equipo borra" on public.ingresantes;
create policy "ingresantes el equipo borra"
  on public.ingresantes for delete to authenticated
  using ((select public.es_equipo()));


-- ------------------------------------------------------------
-- 2. ANOTARSE
--
-- El número se limpia acá y no en el teléfono, para que lo que llega
-- al panel sea siempre igual. Se acepta como lo escribe la gente:
-- «221 15 555-1234», «0221 155551234», «+54 9 221 555 1234». Si viene
-- sin país se asume Argentina y se le pone el 549; el 0 de la
-- característica y el 15 del celular se sacan.
-- ------------------------------------------------------------
create or replace function public.anotar_ingresante(
  p_marca     text,
  p_nombre    text,
  p_telefono  text,
  p_carrera   text,
  p_localidad text
) returns void
language plpgsql security definer set search_path = public as $fn$
declare
  v_nombre text := btrim(coalesce(p_nombre, ''));
  v_loc    text := nullif(btrim(coalesce(p_localidad, '')), '');
  v_crudo  text := btrim(coalesce(p_telefono, ''));
  v_tel    text := regexp_replace(v_crudo, '[^0-9]', '', 'g');
  v_estaba boolean := false;
begin
  if p_marca is null or p_marca !~ '^[0-9a-f]{32}$' then
    raise exception 'marca inválida';
  end if;
  if char_length(v_nombre) not between 2 and 80 then
    raise exception 'falta el nombre';
  end if;
  if p_carrera not in ('ts', 'tgcr', 'fono', 'nose') then
    raise exception 'carrera inválida';
  end if;
  if char_length(coalesce(v_loc, '')) > 80 then
    raise exception 'la localidad es muy larga';
  end if;

  /* Argentina sin el +: 0221 15 5551234 -> 221 5551234 -> 549 221 5551234.
     El 15 va pegado a la característica (2, 3 o 4 cifras) y se saca solo
     si lo que queda tiene las 10 cifras de un número argentino. */
  if left(v_crudo, 1) <> '+' and left(v_tel, 2) <> '54' then
    v_tel := regexp_replace(v_tel, '^0', '');
    if char_length(v_tel) = 12 then
      v_tel := regexp_replace(v_tel, '^([0-9]{2,4}?)15([0-9]{6,8})$', '\1\2');
    end if;
    if char_length(v_tel) = 10 then
      v_tel := '549' || v_tel;
    end if;
  elsif left(v_tel, 2) = '54' and substr(v_tel, 3, 1) <> '9' and char_length(v_tel) = 12 then
    -- +54 221 5551234: a WhatsApp le falta el 9 de los celulares.
    v_tel := '549' || substr(v_tel, 3);
  end if;
  if v_tel !~ '^[0-9]{10,15}$' then
    raise exception 'el número no parece un WhatsApp';
  end if;

  /* El freno de caudal, el mismo de Avisanos: lo que llena la base es el
     bucle, no la fila. Treinta por minuto sobra para un fin de año. */
  if (select count(*) from public.ingresantes
       where creado_at > now() - interval '1 minute') >= 30 then
    raise exception 'Llegaron demasiadas juntas.' using errcode = '54000';
  end if;

  /* Una fila por número y una por teléfono: si ya estaba, se pisa y se
     guarda si el equipo ya la había sumado. */
  select coalesce(bool_or(en_el_grupo), false) into v_estaba
    from public.ingresantes where telefono = v_tel or marca = p_marca;
  delete from public.ingresantes where telefono = v_tel or marca = p_marca;

  insert into public.ingresantes (nombre, telefono, carrera, localidad, marca, en_el_grupo)
  values (v_nombre, v_tel, p_carrera, v_loc, p_marca, v_estaba);
end;
$fn$;


-- ------------------------------------------------------------
-- 3. BORRARSE
--
-- Desde el mismo teléfono que la anotó. Devuelve si había algo, para
-- que la pantalla no diga «te borramos» cuando no estaba.
-- ------------------------------------------------------------
create or replace function public.borrar_ingresante(p_marca text)
returns boolean
language plpgsql security definer set search_path = public as $fn$
declare
  v_hubo int;
begin
  if p_marca is null or p_marca !~ '^[0-9a-f]{32}$' then
    return false;
  end if;
  delete from public.ingresantes where marca = p_marca;
  get diagnostics v_hubo = row_count;
  return v_hubo > 0;
end;
$fn$;

revoke all on function public.anotar_ingresante(text, text, text, text, text) from public;
revoke all on function public.borrar_ingresante(text)                         from public;
grant execute on function public.anotar_ingresante(text, text, text, text, text) to anon, authenticated;
grant execute on function public.borrar_ingresante(text)                         to anon, authenticated;
