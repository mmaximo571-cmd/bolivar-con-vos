--   actividad        (linea = 'frente')  -> desde el 30/9, igual.
--   ninguno marca `avisar`: los eventos avisan solos, por categoría
--   (sección 8 y `supabase/functions/avisos`).
--   ninguno toca la alarma de mesas (`alarma = 'ninguna'`).
