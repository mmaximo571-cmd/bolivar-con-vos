-- ============================================================
-- 1. LA TABLA
--
-- Escrita tal como está hoy en la base (se leyó el 29/9/2026), así el
-- archivo sirve para rearmarla de cero en un proyecto nuevo. En el
-- proyecto que ya existe, ninguno de estos `if not exists` hace nada.
-- ============================================================

create table if not exists public.publicaciones (
  id          bigint generated by default as identity primary key,
  tipo        text not null default 'novedad',
  linea       text not null default 'info',
  titulo      text not null,
  cuerpo      text,
  fecha_desde date,
  fecha_hasta date,
  hora        text,
  lugar       text,
  imagen_url  text,
  link_url    text,
  destacado   boolean not null default false,
  publicado   boolean not null default true,
  creado_at   timestamptz not null default now(),
  alarma      text,
  periodo     text,
  avisar      boolean not null default false,
  avisar_at   timestamptz
);

-- `evento` es un paro, un grupo de estudio, una charla: algo con fecha
-- y lugar. `fecha` es una fecha clave del calendario académico.
-- `novedad` es lo que no tiene fecha propia.
alter table public.publicaciones drop constraint if exists publicaciones_tipo_check;
alter table public.publicaciones add constraint publicaciones_tipo_check
  check (tipo in ('novedad', 'evento', 'fecha'));

alter table public.publicaciones drop constraint if exists publicaciones_linea_check;
alter table public.publicaciones add constraint publicaciones_linea_check
  check (linea in ('frente', 'gremial', 'info', 'saberes'));

-- Si alimenta la alarma de mesas, tiene que decir de qué mesa.
alter table public.publicaciones drop constraint if exists publicaciones_alarma_valida;
alter table public.publicaciones add constraint publicaciones_alarma_valida
  check (alarma is null or alarma = 'ninguna'
         or (alarma in ('inscripcion', 'mesa')
             and periodo is not null and btrim(periodo) <> ''));


-- ============================================================
-- 2. QUIÉN CARGÓ CADA COSA  ·  columna nueva
--
-- Hace falta para moderar: si un paro entra sin publicar y alguien del
-- equipo lo tiene que aprobar, tiene que poder ver quién lo mandó. Y
-- para que quien carga pueda borrar lo SUYO sin poder tocar lo de otro.
--
-- Queda en null en todo lo cargado hasta hoy, y eso está bien: no se
-- puede inventar el autor de algo viejo. `on delete set null` para que
-- borrar una cuenta no se lleve publicaciones puestas.
-- ============================================================

alter table public.publicaciones
  add column if not exists creado_por uuid
  references auth.users(id) on delete set null;

-- Se llena sola con quien está logueado: así no depende de que la
-- pantalla se acuerde de mandarla, y la política de abajo obliga a que
-- sea el que escribe, así que tampoco se puede falsear desde el cliente.
alter table public.publicaciones
  alter column creado_por set default auth.uid();

create index if not exists publicaciones_creado_por_idx
  on public.publicaciones (creado_por) where creado_por is not null;

-- La bandeja de paros esperando visto bueno entra por acá.
create index if not exists publicaciones_pendientes_idx
  on public.publicaciones (creado_at desc)
  where publicado = false;


