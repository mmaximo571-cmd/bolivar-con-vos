-- ============================================================
-- 6. `comunicacion`  ·  novedades y eventos
--
-- Reemplaza las cuatro políticas que hoy están en `tabla-buzon.sql`
-- acotadas a `tipo = 'novedad'`. Los nombres son los mismos a propósito:
-- el `drop policy if exists` de cada una las pisa, así correr este
-- archivo deja una sola versión y no dos que se sumen.
-- ============================================================

-- Qué puede cargar y editar, en una sola función para no repetir la
-- condición en tres políticas y que se despeguen con el tiempo.
create or replace function public.publicacion_de_comunicacion(
  p_tipo      text,
  p_linea     text,
  p_titulo    text,
  p_alarma    text,
  p_avisar    boolean,
  p_publicado boolean
) returns boolean language sql immutable as $$
  select
    coalesce(p_alarma, '') = 'ninguna'
    and (
      -- Las novedades siguen como estaban (pueden avisar al celular:
      -- así las usa el buzón desde el 24/9).
      p_tipo = 'novedad'
      or (
        p_tipo = 'evento'
        -- Un evento no hace sonar teléfonos ni se parece a una mesa.
        and p_avisar = false
        and p_titulo !~* '^\s*(inscripci[óo]n a la mesa|mesa de examen)'
        and (
             p_linea = 'saberes'                          -- grupo de estudio
          or (p_linea = 'gremial' and p_publicado = false) -- paro: lo publica el equipo
        )
      )
    );
$$;

revoke all on function public.publicacion_de_comunicacion(text,text,text,text,boolean,boolean)
  from public, anon;
grant execute on function public.publicacion_de_comunicacion(text,text,text,text,boolean,boolean)
  to authenticated;

-- VE lo suyo aunque no esté publicado: el que manda un paro tiene que
-- poder ver en qué quedó.
drop policy if exists "publicaciones comunicacion ve novedades" on public.publicaciones;
create policy "publicaciones comunicacion ve novedades"
  on public.publicaciones for select to authenticated
  using (public.es_comunicacion()
         and (tipo in ('novedad', 'evento') or creado_por = auth.uid()));

drop policy if exists "publicaciones comunicacion carga novedades" on public.publicaciones;
create policy "publicaciones comunicacion carga novedades"
  on public.publicaciones for insert to authenticated
  with check (public.es_comunicacion()
              and creado_por = auth.uid()
              and public.publicacion_de_comunicacion(
                    tipo, linea, titulo, alarma, avisar, publicado));

-- Edita, pero no puede pasar un paro a publicado: la condición también
-- se pide DESPUÉS del cambio (`with check`).
drop policy if exists "publicaciones comunicacion edita novedades" on public.publicaciones;
create policy "publicaciones comunicacion edita novedades"
  on public.publicaciones for update to authenticated
  using (public.es_comunicacion()
         and public.publicacion_de_comunicacion(
               tipo, linea, titulo, alarma, avisar, publicado))
  with check (public.es_comunicacion()
              and public.publicacion_de_comunicacion(
                    tipo, linea, titulo, alarma, avisar, publicado));

-- Borra las novedades (como hasta hoy) y los eventos QUE CARGÓ ÉL. Un
-- compañero tiene que poder deshacer su propio error sin poder borrar
-- el grupo de estudio de otro.
drop policy if exists "publicaciones comunicacion borra novedades" on public.publicaciones;
create policy "publicaciones comunicacion borra novedades"
  on public.publicaciones for delete to authenticated
  using (public.es_comunicacion()
         and (tipo = 'novedad'
              or (tipo = 'evento' and creado_por = auth.uid())));


