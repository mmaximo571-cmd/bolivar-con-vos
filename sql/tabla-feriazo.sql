-- ============================================================
-- FERIAZO · ESTUDIANTES Y TRABAJADORES
--
-- La pantalla `feriazo/`: los emprendimientos de la gente de la facu
-- (estudiantes, docentes y no docentes), cada uno con su Instagram, una
-- descripción corta, el rubro y una foto o el logo.
--
-- NO ES UNA TIENDA. No hay precios, ni carrito, ni «comprar»: es un
-- lugar para conocerse y que el Instagram de cada quien circule entre
-- compañeras y compañeros. Por eso la tabla no tiene ni una columna de
-- plata, y no conviene agregársela.
--
-- OJO: DOS DE ESTAS DECISIONES CAMBIARON EL 11/11/2026 (quién carga, y
-- que el Instagram sea obligatorio). Lo nuevo está en el bloque 3, al
-- final; lo de acá abajo queda como estaba para que se entienda de
-- dónde viene. «No es una tienda» sigue en pie.
--
-- Lo decidido con Máximo el 24/10/2026 y cómo queda acá:
--
--   LO CARGA SOLO EL EQUIPO. Quien quiere sumar su emprendimiento le
--   escribe a la agrupación, y alguien lo carga desde `cargar/` (la
--   pestaña Feriazo). Así nadie sube el Instagram de otra persona ni
--   algo que no va. Cualquiera LEE lo publicado, sin cuenta.
--
--   QUIÉN CARGA: el equipo y comunicación, `modera_buzon()` (ver
--   `sql/tabla-buzon.sql`). Los dos y no solo el equipo porque el
--   24/10/2026 no había ninguna cuenta con rol `equipo`: la única que
--   carga es la de comunicación, y desde `cargar/`, no desde el panel.
--
--   PARA BAJARLO O CAMBIARLO, se pide por Decilo y lo hace el equipo.
--   Bajarlo es borrar la fila Y la foto del depósito: si alguien pide
--   que lo saquen, tiene que desaparecer de verdad.
--
-- LA FOTO va al depósito `fotos` (`sql/tabla-fotos.sql`) con nombre
-- `feriazo-…`. Ese depósito solo deja subir al equipo; acá se le abre a
-- comunicación ÚNICAMENTE lo que empieza con `feriazo-`, para que no
-- pueda tocar las fotos de «¿Quiénes somos?» ni las del Consejo.
--
-- Cómo se corre:
--   supabase.com -> proyecto -> SQL Editor -> New query -> pegar -> Run
-- Se puede correr más de una vez sin romper nada. Necesita que antes
-- estén `sql/tabla-buzon.sql` (de ahí sale `modera_buzon()`) y
-- `sql/tabla-fotos.sql` (el depósito).
--
-- ESTADO: ensayado el 24/10/2026 con begin/rollback (7 rechazos
-- esperados: instagram repetido o con @, foto que no es `feriazo-`,
-- estudiante que carga o sube foto, sin cuenta que carga o borra), y
-- aplicado en producción ese mismo día (migración `tabla_feriazo`).
-- ============================================================


-- ------------------------------------------------------------
-- 1. LOS EMPRENDIMIENTOS
-- ------------------------------------------------------------
create table if not exists public.feriazo (
  id            bigint generated by default as identity primary key,
  nombre        text not null check (length(btrim(nombre)) between 2 and 80),
  -- Sin la @ y sin la dirección: solo el usuario. La app arma el link.
  -- Son las reglas de Instagram: letras, números, punto y guion bajo.
  instagram     text not null check (instagram ~ '^[a-z0-9._]{1,30}$'),
  -- Corta a propósito: es una tarjeta, no un catálogo. Lo demás está
  -- en su Instagram.
  descripcion   text not null check (length(btrim(descripcion)) between 10 and 240),
  -- La lista vive acá y en `RUBROS_FERIAZO` de `feriazo/index.html` y
  -- `cargar/feriazo.js`: si se agrega uno, se agrega en los tres.
  rubro         text not null check (rubro in
                  ('comida', 'ropa', 'arte', 'bienestar', 'plantas',
                   'libros', 'servicios', 'otros')),
  -- Es el «estudiantes y trabajadores» del nombre.
  quien         text not null check (quien in ('estudiante', 'docente', 'nodocente')),
  -- Opcional: una docente da clases en más de una carrera.
  carrera       text check (carrera in ('ts', 'fono', 'tgcr')),
  -- La dirección pública de la foto, y su nombre en el depósito para
  -- poder borrarla de verdad.
  foto          text check (foto is null or foto ~ '^https://'),
  foto_archivo  text check (foto_archivo is null or foto_archivo ~ '^feriazo-[a-z0-9-]+\.jpg$'),
  publicado     boolean not null default true,
  creado_at     timestamptz not null default now(),
  actualizado_at timestamptz not null default now()
);

-- Dos emprendimientos con el mismo Instagram es el mismo cargado dos
-- veces: mejor que la base lo frene a que salga repetido.
create unique index if not exists feriazo_instagram_unico on public.feriazo (instagram);

alter table public.feriazo enable row level security;

revoke all on public.feriazo from anon, authenticated;
grant select on public.feriazo to anon, authenticated;
grant insert, update, delete on public.feriazo to authenticated;

-- Dos políticas de lectura y no una con «or»: `anon` no puede llamar
-- `modera_buzon()`, y Postgres no promete cortar el «or» antes. Es lo
-- mismo que se encontró en el congreso el 7/10/2026.
drop policy if exists "feriazo lectura publica" on public.feriazo;
create policy "feriazo lectura publica" on public.feriazo
  for select using (publicado);

drop policy if exists "feriazo el equipo ve todo" on public.feriazo;
create policy "feriazo el equipo ve todo" on public.feriazo
  for select to authenticated
  using ((select public.modera_buzon()));

drop policy if exists "feriazo el equipo carga" on public.feriazo;
create policy "feriazo el equipo carga" on public.feriazo
  for insert to authenticated
  with check ((select public.modera_buzon()));

drop policy if exists "feriazo el equipo edita" on public.feriazo;
create policy "feriazo el equipo edita" on public.feriazo
  for update to authenticated
  using ((select public.modera_buzon()))
  with check ((select public.modera_buzon()));

drop policy if exists "feriazo el equipo borra" on public.feriazo;
create policy "feriazo el equipo borra" on public.feriazo
  for delete to authenticated
  using ((select public.modera_buzon()));

create or replace function public.tocar_feriazo()
returns trigger language plpgsql set search_path = public as $$
begin
  new.actualizado_at = now();
  return new;
end $$;

drop trigger if exists al_tocar_feriazo on public.feriazo;
create trigger al_tocar_feriazo before update on public.feriazo
  for each row execute function public.tocar_feriazo();


-- ------------------------------------------------------------
-- 2. LAS FOTOS
--
-- Las políticas del equipo de `sql/tabla-fotos.sql` siguen como están.
-- Estas se SUMAN (en Postgres las políticas permisivas se suman con
-- «or») y solo valen para los nombres `feriazo-…`.
-- ------------------------------------------------------------
drop policy if exists "fotos feriazo sube comunicacion" on storage.objects;
create policy "fotos feriazo sube comunicacion"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'fotos' and name like 'feriazo-%'
              and (select public.modera_buzon()));

drop policy if exists "fotos feriazo borra comunicacion" on storage.objects;
create policy "fotos feriazo borra comunicacion"
  on storage.objects for delete to authenticated
  using (bucket_id = 'fotos' and name like 'feriazo-%'
         and (select public.modera_buzon()));


